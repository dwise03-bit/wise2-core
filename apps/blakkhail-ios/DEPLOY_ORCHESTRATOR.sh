#!/bin/bash

# BLAKKHAIL iOS - Complete Deployment Orchestrator
# Manages: device detection → code signing → build → install → test
# Usage: ./DEPLOY_ORCHESTRATOR.sh

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m'

# Global state
TIMESTAMP=$(date +%s)
LOG_FILE="deployment-${TIMESTAMP}.log"
BUILD_DIR="./build-${TIMESTAMP}"
DEVICES_FOUND=0
XCODE_PATH=""

# ============================================================================
# PHASE 1: Environment & Prerequisites
# ============================================================================

phase1_verify_environment() {
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo -e "${BLUE}PHASE 1: Environment Verification${NC}"
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo ""

  # Check Xcode
  echo -e "${YELLOW}1.1 Checking Xcode installation...${NC}"
  XCODE_PATH=$(xcode-select -p 2>/dev/null || echo "")
  if [ -z "$XCODE_PATH" ]; then
    echo -e "${RED}❌ Xcode not found${NC}"
    echo "Install Xcode from App Store or run: xcode-select --install"
    exit 1
  fi
  echo -e "${GREEN}✅ Xcode: ${XCODE_PATH}${NC}"

  # Check Xcode command line tools
  echo -e "${YELLOW}1.2 Checking Xcode CLI tools...${NC}"
  if ! command -v xcodebuild &>/dev/null; then
    echo -e "${RED}❌ xcodebuild not found${NC}"
    exit 1
  fi
  XCODEBUILD_VERSION=$(xcodebuild -version | head -1)
  echo -e "${GREEN}✅ ${XCODEBUILD_VERSION}${NC}"

  # Create build directory
  echo -e "${YELLOW}1.3 Preparing build environment...${NC}"
  mkdir -p "$BUILD_DIR"
  echo -e "${GREEN}✅ Build directory: ${BUILD_DIR}${NC}"
  echo ""
}

# ============================================================================
# PHASE 2: Device Detection
# ============================================================================

phase2_detect_devices() {
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo -e "${BLUE}PHASE 2: Device Detection${NC}"
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo ""

  echo -e "${YELLOW}2.1 Scanning for connected iOS devices...${NC}"
  echo "Please ensure:"
  echo "  • iPhones are connected via USB"
  echo "  • iPhones are unlocked"
  echo "  • Trust dialog has been tapped on devices"
  echo ""

  sleep 3

  # Try to list devices via Xcode's device discovery
  echo -e "${YELLOW}2.2 Querying Xcode device list...${NC}"

  # This will show connected devices
  xcrun devicectl list devices 2>/dev/null || true

  echo ""
  echo -e "${YELLOW}2.3 Device Detection Summary${NC}"
  echo "If devices are not listed above:"
  echo "  1. Check USB connections"
  echo "  2. Tap 'Trust' on each iPhone"
  echo "  3. Restart Xcode"
  echo ""
}

# ============================================================================
# PHASE 3: Code Signing Setup
# ============================================================================

phase3_code_signing() {
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo -e "${BLUE}PHASE 3: Code Signing & Provisioning${NC}"
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo ""

  echo -e "${YELLOW}3.1 Checking code signing identities...${NC}"

  # List available signing identities
  security find-identity -v -p codesigning 2>/dev/null | grep "iPhone Developer" || {
    echo -e "${YELLOW}⚠️  No iPhone Developer certificate found${NC}"
    echo ""
    echo "To fix:"
    echo "  1. Open Xcode"
    echo "  2. Go to Settings → Accounts"
    echo "  3. Add your Apple Developer Account"
    echo "  4. Select the account and click 'Manage Certificates'"
    echo "  5. Create 'iOS Development' certificate if needed"
    echo ""
  }

  echo -e "${YELLOW}3.2 Automatic Code Signing Status${NC}"
  echo "The project uses automatic code signing (recommended)"
  echo "  • Team: Will be auto-selected from your account"
  echo "  • Certificates: Auto-generated by Xcode"
  echo "  • Provisioning: Auto-created for connected devices"
  echo ""
}

# ============================================================================
# PHASE 4: Build
# ============================================================================

phase4_build() {
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo -e "${BLUE}PHASE 4: Building BLAKKHAIL iOS App${NC}"
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo ""

  echo -e "${YELLOW}4.1 Cleaning previous builds...${NC}"
  rm -rf DerivedData build/ "$BUILD_DIR"/*.build
  echo -e "${GREEN}✅ Clean complete${NC}"
  echo ""

  echo -e "${YELLOW}4.2 Building for physical devices...${NC}"
  echo "Configuration: Release"
  echo "SDK: iphoneos"
  echo "Architecture: arm64"
  echo ""

  if xcodebuild \
    -scheme Blakkhail \
    -configuration Release \
    -sdk iphoneos \
    -derivedDataPath "$BUILD_DIR/DerivedData" \
    -arch arm64 \
    build 2>&1 | tee "${BUILD_DIR}/build.log"; then
    echo -e "${GREEN}✅ Build successful${NC}"
  else
    echo -e "${RED}❌ Build failed${NC}"
    echo "See build log: ${BUILD_DIR}/build.log"
    exit 1
  fi
  echo ""
}

# ============================================================================
# PHASE 5: Install to Devices
# ============================================================================

phase5_install() {
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo -e "${BLUE}PHASE 5: Installing to Connected Devices${NC}"
  echo -e "${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
  echo ""

  echo -e "${YELLOW}5.1 Building for installation...${NC}"
  if xcodebuild \
    -scheme Blakkhail \
    -configuration Release \
    -sdk iphoneos \
    -derivedDataPath "$BUILD_DIR/DerivedData" \
    build-for-testing 2>&1 | tail -10; then
    echo -e "${GREEN}✅ Install build ready${NC}"
  else
    echo -e "${RED}❌ Install build failed${NC}"
    exit 1
  fi
  echo ""

  echo -e "${YELLOW}5.2 Installation Instructions${NC}"
  echo ""
  echo "To install on iPhone 1:"
  echo "  1. In Xcode: Product → Destination → [Your iPhone]"
  echo "  2. Product → Run (Cmd + R)"
  echo "  3. Wait for installation to complete"
  echo ""
  echo "To install on iPhone 2:"
  echo "  1. Disconnect iPhone 1 or select iPhone 2"
  echo "  2. Product → Destination → [iPhone 2]"
  echo "  3. Product → Run (Cmd + R)"
  echo ""
}

